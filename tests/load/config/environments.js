export function getEnvironment() {
    const baseUrl = (__ENV.BASE_URL || 'http://127.0.0.1:8090').replace(/\/+$/, '');
    if (!/^https?:\/\/(?:localhost|127\.0\.0\.1)(?::\d+)?(?:\/.*)?$/i.test(baseUrl)) {
        throw new Error('BASE_URL must point to localhost or 127.0.0.1. Production URLs are prohibited.');
    }
    const runId = __ENV.K6_RUN_ID || '';
    if (!/^[a-f0-9]{32}$/i.test(runId)) {
        throw new Error('K6_RUN_ID must be a 32-character hexadecimal ID generated by tests/load/run-test.ps1.');
    }
    const adminPath = normalizePath(__ENV.ADMIN_PATH || '/admin');

    return {
        baseUrl,
        runId,
        adminPath,
        loginUrl: `${baseUrl}${adminPath}/login`,
        dashboardUrl: `${baseUrl}${adminPath}`,
        timeout: __ENV.REQUEST_TIMEOUT || '30s',
        thinkTimeSeconds: Number(__ENV.THINK_TIME_SECONDS || 1),
        scenario: (__ENV.LOAD_SCENARIO || 'smoke').toLowerCase(),
        testProfile: (__ENV.TEST_PROFILE || 'smoke').toLowerCase(),
        highLoadConfirmation: __ENV.CONFIRM_HIGH_LOAD === 'I_CONFIRM_HIGH_LOAD',
    };
}

export function normalizePath(path) {
    const value = String(path || '/admin').trim();
    if (!value.startsWith('/')) {
        return `/${value}`;
    }
    return value.replace(/\/+$/, '');
}

